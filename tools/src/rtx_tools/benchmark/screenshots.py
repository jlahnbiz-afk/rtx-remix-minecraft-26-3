"""Documentation screenshots: capture the marked still shots and export them.

The shot set is authored in game with `/rtx shot mark <name>` and lives in
`tools/assets/shots/docs.shots.json`, a git-tracked file the mod writes
to directly when the harness launched the client. Other sets beside it, such as a
set of visual checks, are captured the same way with `--set`, into
`build/screenshots/<set>/`, optionally in another imported world or art pack. A refresh stages the pinned
world and art pack, runs the client in `stills` trigger mode, waits for the
`stills-complete` heartbeat, and converts each captured PNG into a JPEG under
`build/screenshots/`. The guides embed the images as GitHub attachments, so a
maintainer uploads them from there. The provenance in `README.md` beside them
is rewritten from the same inputs so it cannot drift from the images.
"""

from __future__ import annotations

import json
import re
import subprocess
import time
from pathlib import Path
from typing import Any

from PIL import Image

from .. import client, sdk
from . import runner, util

SHOT_SET = "docs"
# Version 2 names the cloud style; version 1 had only a procedural-clouds flag.
SHOT_SET_VERSIONS = (1, 2)
SHOTS_DIR = util.ASSETS_DIR / "shots"
SHOT_SET_PATH = SHOTS_DIR / f"{SHOT_SET}.shots.json"
# The guides embed the images as GitHub attachments, so a refresh writes them
# outside the tracked tree for a maintainer to upload.
OUTPUT_DIR = util.PROJECT_DIR / "build" / "screenshots"
README_PATH = OUTPUT_DIR / "README.md"
MAX_EDGE_PX = 1600
JPEG_QUALITY = 85
PROVENANCE_BEGIN = "<!-- provenance: generated by `rtx screenshots refresh`, do not edit by hand -->"
PROVENANCE_END = "<!-- provenance: end -->"
STILLS_COMPLETE_PHASE = "stills-complete"
STILLS_FAILED_PHASE = "stills-failed"

WEATHER_LABELS = {"clear": "clear", "rain": "rain", "thunder": "thunderstorm"}
# The mod's rule for a name that becomes a file under the camera directory
# (CameraNames.java). A shot name becomes <name>.png and <name>.jpg here, and
# the refresh deletes and writes under it, so a set read from disk is held to
# the rule before any file is touched.
SHOT_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
WINDOWS_RESERVED_RE = re.compile(r"^(?:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\..*)?$", re.IGNORECASE)


def shot_set_path(set_name: str = SHOT_SET) -> Path:
    """Where a named shot set lives."""
    if not is_shot_name(set_name):
        raise RuntimeError(f"shot set name is not a single file name: {set_name!r}")
    return SHOTS_DIR / f"{set_name}.shots.json"


def output_dir(set_name: str = SHOT_SET) -> Path:
    """Where a set's JPEGs go: the documentation set at the top, any other in its own folder."""
    return OUTPUT_DIR if set_name == SHOT_SET else OUTPUT_DIR / set_name


def shot_clouds(shot: dict[str, Any]) -> str:
    """The cloud style a shot shows, from either shot set version."""
    clouds = shot.get("clouds")
    if isinstance(clouds, str):
        return clouds
    return "procedural" if shot.get("proceduralClouds") else "classic"


def load_shot_set(path: Path = SHOT_SET_PATH) -> list[dict[str, Any]]:
    """The shots in a set, in file order. A missing file is an empty set."""
    if not path.exists():
        return []
    data = util.read_json(path)
    if not isinstance(data, dict) or data.get("version") not in SHOT_SET_VERSIONS:
        raise RuntimeError(f"{path} is not a version {' or '.join(map(str, SHOT_SET_VERSIONS))} shot set")
    shots = data.get("shots")
    if not isinstance(shots, list) or not all(isinstance(shot, dict) for shot in shots):
        raise RuntimeError(f"{path} has a malformed shots array")
    for shot in shots:
        if not is_shot_name(shot.get("name")):
            raise RuntimeError(f"{path} names a shot that is not a single file name: {shot.get('name')!r}")
    return shots


def is_shot_name(name: object) -> bool:
    """Whether `name` is a safe single file name on every supported platform."""
    return (
        isinstance(name, str)
        and bool(SHOT_NAME_RE.match(name))
        and not WINDOWS_RESERVED_RE.match(name)
        and name not in (".", "..")
    )


def select_shots(shots: list[dict[str, Any]], names: list[str], set_name: str = SHOT_SET) -> list[dict[str, Any]]:
    """Shots whose names were asked for, in set order; every name must exist."""
    if not names:
        return list(shots)
    known = {shot["name"] for shot in shots}
    missing = [name for name in names if name not in known]
    if missing:
        raise RuntimeError(
            f"no shot named {', '.join(missing)} in {set_name}.shots.json; "
            f"mark it in game with /rtx shot mark <name> (have: {', '.join(sorted(known)) or 'none'})"
        )
    wanted = set(names)
    return [shot for shot in shots if shot["name"] in wanted]


def export_jpeg(source: Path, destination: Path, *, max_edge: int = MAX_EDGE_PX, quality: int = JPEG_QUALITY) -> None:
    """Resize to `max_edge` on the longest side (never upscale) and save as JPEG."""
    with Image.open(source) as image:
        rgb = image.convert("RGB")
        width, height = rgb.size
        scale = max_edge / max(width, height)
        if scale < 1.0:
            rgb = rgb.resize((max(1, round(width * scale)), max(1, round(height * scale))), Image.Resampling.LANCZOS)
        destination.parent.mkdir(parents=True, exist_ok=True)
        rgb.save(destination, "JPEG", quality=quality, optimize=True)


def provenance_text(
    *,
    world_version: str,
    pack_names: list[str],
    width: int,
    height: int,
    shots: list[dict[str, Any]],
) -> str:
    """The generated README section: how the images were made and what each one shows."""
    packs = " and ".join(f"`{name}`" for name in pack_names) if pack_names else "no resource pack"
    lines = [
        PROVENANCE_BEGIN,
        "",
        f"Every world image was captured in the showcase demo world, version {world_version}, "
        f"with {packs} enabled. The client ran at {width}x{height} on the RTX Remix runtime "
        "pinned by this repository's build with the HUD hidden, and each "
        f"capture was resized to {MAX_EDGE_PX} px on its longest edge and saved as JPEG at "
        f"quality {JPEG_QUALITY}.",
        "",
        "Poses are marked in game with `/rtx shot mark <name>` and recaptured with "
        "`rtx screenshots refresh`, so every image below can be retaken from the same spot.",
        "",
        "| Image | Time of day | Weather | Clouds | Path tracing |",
        "|-------|-------------|---------|--------|--------------|",
    ]
    for shot in shots:
        clouds = shot_clouds(shot)
        rtx = "on" if shot.get("rtx", True) else "off"
        weather = WEATHER_LABELS.get(str(shot.get("weather", "clear")), str(shot.get("weather")))
        lines.append(f"| `{shot['name']}.jpg` | {shot.get('timeOfDay', 0)} | {weather} | {clouds} | {rtx} |")
    lines.extend(["", PROVENANCE_END])
    return "\n".join(lines)


def update_readme(existing: str, provenance: str) -> str:
    """Replace the generated section, or append one to a README that has none."""
    begin = existing.find(PROVENANCE_BEGIN)
    end = existing.find(PROVENANCE_END)
    if begin < 0 or end < begin:
        trimmed = existing.rstrip()
        return (trimmed + "\n\n" if trimmed else "") + provenance + "\n"
    end += len(PROVENANCE_END)
    return existing[:begin] + provenance + existing[end:]


def stills_log() -> Path:
    """The client log of a stills capture, in the active launcher's game directory."""
    return util.RUN_DIR / "benchmark" / "stills.log"


def write_stills_trigger(
    config: dict, selection: runner.BenchmarkSelection, names: list[str], set_name: str = SHOT_SET
) -> None:
    settings = config.get("screenshots")
    if not isinstance(settings, dict):
        settings = {}
    extra: dict[str, Any] = {"shotSet": set_name, "shots": names}
    for key in ("settleFrames", "quietFrames", "maxSettleFrames"):
        if key in settings:
            extra[key] = int(settings[key])
    runner.write_auto_trigger(
        config,
        selection,
        exit_on_complete=True,
        mode="stills",
        disable_world_saving=True,
        extra=extra,
    )


def capture(
    config: dict,
    selection: runner.BenchmarkSelection,
    names: list[str],
    *,
    sdk_variant: str,
    timeout_seconds: int,
    set_name: str = SHOT_SET,
) -> dict[str, Path]:
    """Run the client once in stills mode and return the PNG each shot produced."""
    runner.ensure_no_live_client()
    launcher = client.active()
    launcher.check()
    arch = runner.host_arch()
    runner.fetch_sdk(sdk_variant, arch, auto_restage=sdk.configured_sdk_auto_restage(config))
    launcher.prepare(arch, build=True)
    runner.install_fixtures(config, selection, pin_display=True)

    screenshots_dir = util.RUN_DIR / "benchmark" / "screenshots"
    screenshots_dir.mkdir(parents=True, exist_ok=True)
    status_path = util.RUN_DIR / "benchmark" / "results" / runner.BENCHMARK_STATUS_FILE
    status_path.parent.mkdir(parents=True, exist_ok=True)
    status_path.unlink(missing_ok=True)
    expected = {name: screenshots_dir / f"{name}.png" for name in names}
    for png in expected.values():
        png.unlink(missing_ok=True)
    write_stills_trigger(config, selection, names, set_name)

    runner.kill_leftovers()
    runner.park_stale_runtime_state()
    log_path = stills_log()
    log_path.unlink(missing_ok=True)
    print(f"Launching Minecraft for {len(names)} still shot(s): {', '.join(names)}")
    failure = ""
    process_started_ns = time.time_ns()
    with (
        log_path.open("w", encoding="utf-8", errors="replace") as log,
        runner.started_client(
            client.LaunchRequest(
                arch=arch,
                env=runner.gradle_env(),
                stdout=log,
                stderr=log,
                quick_play_world=runner.BENCHMARK_SAVE_NAME,
                preset=runner.configured_preset_value(config),
                quiet=True,
            )
        ) as proc,
    ):
        start = time.time()
        last_phase = None
        complete = False
        while time.time() - start < timeout_seconds:
            time.sleep(2)
            status = runner.read_benchmark_status(status_path)
            phase = status.get("phase") if status else None
            if phase != last_phase and phase:
                print(f"  {phase}")
                last_phase = phase
            if phase == STILLS_COMPLETE_PHASE:
                complete = True
                break
            if phase == STILLS_FAILED_PHASE:
                failure = "StillsFailed"
                break
            if proc.poll() is not None:
                break
            launcher_logs = launcher.log_files(process_started_ns)
            if fatal := runner.classify_run_failure(runner.read_run_log_best_effort(log_path, *launcher_logs), ""):
                failure = fatal
                break
        if not complete and not failure:
            failure = "Timeout" if proc.poll() is None else "ProcessExited"
        if proc.poll() is None:
            try:
                proc.wait(timeout=runner.post_result_process_wait_seconds(config) if complete else 5)
            except subprocess.TimeoutExpired:
                runner.terminate_process(proc, "game client")
    runner.kill_leftovers()

    missing = [name for name, png in expected.items() if not png.exists()]
    if failure or missing:
        detail = f" ({failure})" if failure else ""
        logs = ", ".join(str(path) for path in [log_path, *launcher.log_files(process_started_ns)])
        raise RuntimeError(
            f"still shot capture did not finish{detail}; missing {', '.join(missing) or 'nothing'}. Client logs: {logs}"
        )
    return expected


def resolve_selection(config: dict) -> runner.BenchmarkSelection:
    world = runner.resolve_world_name(config)
    runner.ensure_world_staged(config, world)
    return runner.configure_benchmark_selection(config, require_camera=False)


def enabled_pack_names(config: dict) -> list[str]:
    names = ["fabric"]
    art = runner.configured_resource_pack(config)
    mode = str(art.get("mode") or "none").strip().lower()
    if mode == "pinned":
        names.append(f"{art.get('name')} {art.get('version')}".strip())
    elif mode == "local":
        names.append("a local art pack")
    return names


def refresh(
    names: list[str],
    *,
    sdk_variant: str = "release",
    timeout_seconds: int = 1800,
    set_name: str = SHOT_SET,
    world: str | None = None,
    resource_pack: str | None = None,
) -> int:
    runner.set_runtime_resource_pack_override(resource_pack)
    config = runner.load_config()
    if world:
        # An imported local save needs only its name.
        config["world"] = {"name": world}
    path = shot_set_path(set_name)
    shots = select_shots(load_shot_set(path), names, set_name)
    if not shots:
        print(f"No shots in {path}. Launch with rtx launch and mark poses with /rtx shot mark <name>.")
        return 1
    destination_dir = output_dir(set_name)
    readme_path = destination_dir / README_PATH.name
    # Before the world is staged, which can download it.
    client.active().check()
    selection = resolve_selection(config)
    captured = capture(
        config,
        selection,
        [shot["name"] for shot in shots],
        sdk_variant=sdk_variant,
        timeout_seconds=timeout_seconds,
        set_name=set_name,
    )
    for name, png in captured.items():
        destination = destination_dir / f"{name}.jpg"
        export_jpeg(png, destination)
        print(f"Wrote {destination.relative_to(util.PROJECT_DIR)}")

    if names:
        # The provenance describes one capture of the whole set; a partial
        # refresh would stamp images it did not retake with this run's world,
        # packs, and scene state.
        readme = readme_path.relative_to(util.PROJECT_DIR)
        print(f"Left {readme} alone: a partial refresh; run a full one to regenerate it")
        return 0

    render = config.get("render")
    if not isinstance(render, dict):
        render = {}
    provenance = provenance_text(
        world_version=str(selection.version or "").lstrip("v") or "unknown",
        pack_names=enabled_pack_names(config),
        width=int(render.get("overrideWidth") or 1920),
        height=int(render.get("overrideHeight") or 1080),
        shots=shots,
    )
    existing = readme_path.read_text(encoding="utf-8") if readme_path.exists() else ""
    readme_path.write_text(update_readme(existing, provenance), encoding="utf-8")
    print(f"Updated {readme_path.relative_to(util.PROJECT_DIR)}")
    return 0


def list_shots(*, as_json: bool = False, set_name: str = SHOT_SET) -> int:
    path = shot_set_path(set_name)
    shots = load_shot_set(path)
    if as_json:
        print(json.dumps(shots, indent=2))
        return 0
    if not shots:
        print(f"No shots in {path}. Launch with rtx launch and mark poses with /rtx shot mark <name>.")
        return 0
    for shot in shots:
        clouds = f", {shot_clouds(shot)} clouds"
        rtx = "" if shot.get("rtx", True) else ", rtx off"
        print(
            f"{shot['name']}: {shot['x']:.1f} {shot['y']:.1f} {shot['z']:.1f} "
            f"yaw {shot['yaw']:.1f} pitch {shot['pitch']:.1f}, time {shot['timeOfDay']}, "
            f"{shot['weather']}{clouds}{rtx}"
        )
    return 0
